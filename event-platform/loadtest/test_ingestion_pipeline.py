@allure.feature("Ingestion API")
@allure.story("Event Pipeline")
@allure.severity(allure.severity_level.CRITICAL)
def test_single_event_ingestion(pg_conn):
    """Post one 500KB event, assert 202, then verify it reaches Postgres."""
    event = make_event()
    resp = requests.post(EVENTS_URL, json=event, timeout=10)
    allure.attach(
        json.dumps({"status": resp.status_code, "event_id": event["event_id"]}),
        name="ingestion_response",
        attachment_type=allure.attachment_type.JSON,
    )
    assert resp.status_code == 202, f"Expected 202 Accepted, got {resp.status_code}"

    # Wait for Kafka Connect to flush to Postgres (poll up to 30s)
    cur = pg_conn.cursor()
    found = False
    for _ in range(15):
        cur.execute(
            "SELECT event_id FROM raw_events WHERE event_id = %s",
            (event["event_id"],),
        )
        if cur.fetchone():
            found = True
            break
        time.sleep(2)
    cur.close()

    allure.attach(
        json.dumps({"event_id": event["event_id"], "found_in_postgres": found}),
        name="postgres_verification",
        attachment_type=allure.attachment_type.JSON,
    )
    # Note: If Kafka Connect is unhealthy this may legitimately fail.
    # We assert but accept it as a real test outcome.
    assert found, (
        f"Event {event['event_id']} did not appear in raw_events within 30s. "
        "Kafka Connect sink may be down."
    )


